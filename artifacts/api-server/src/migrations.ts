/**
 * Schema migrations, with EXPLICIT recorded state.
 *
 * What this replaces: until order L-3.4g the schema was a pile of
 * `CREATE TABLE IF NOT EXISTS` plus hand-rolled `addColumnIfMissing` /
 * `PRAGMA table_info` guards, and storeDiscoveryDb.ts said so out loud —
 * "There is no migration framework here". That worked because SQLite was
 * forgiving and because the file was recreated from scratch on every publish
 * anyway. Against a database that actually persists, "the schema is whatever
 * the last boot happened to add" is not a state anybody can reason about.
 *
 * So: an ordered list, each entry applied exactly once, inside a transaction,
 * with its id and name written to `schema_migrations` in the SAME transaction.
 * Either a migration and its record both land or neither does.
 *
 * TYPE MAPPING, applied uniformly (see the ledger for the table-by-table map):
 *   TEXT                            → text
 *   INTEGER                         → bigint
 *   REAL                            → double precision
 *   INTEGER PRIMARY KEY AUTOINCREMENT → bigint GENERATED BY DEFAULT AS IDENTITY
 *
 * `INTEGER → bigint` is not caution for its own sake. SQLite's INTEGER is
 * 64-bit and this schema stores epoch MILLISECONDS in it; `int4` tops out at
 * 2147483647, which epoch-ms passed in 1970. A column of `integer` here would
 * take every timestamp write in the app and turn it into an out-of-range error.
 *
 * `GENERATED BY DEFAULT AS IDENTITY` rather than `ALWAYS`: the rescue seed
 * (rescueSeed.ts) inserts `job_results` rows under their ORIGINAL ids so that
 * `lf_lead_id` keeps pointing at the same lead the Chief already recorded, and
 * `ALWAYS` would refuse those inserts.
 *
 * COLUMN ORDER IS LOAD-BEARING. `getJob` and friends `SELECT *`, and those rows
 * are serialised straight into API responses, so column order is JSON key order
 * and the DARK smoke baseline pins it. Every table below lists its columns in
 * the order the SQLite database had them — base CREATE first, then the columns
 * that arrived later by ALTER, in the order they arrived.
 *
 * THE STANDING RULE: a migration containing DROP or TRUNCATE is never approved.
 * That is not a convention here — assertNoDestructiveMigrations() below is run
 * by the test gate, so a destructive migration cannot reach a database at all.
 */

