// ── The destructive-migration ban ────────────────────────────────────────────

/**
 * DROP and TRUNCATE are refused, statically, before anything runs.
 *
 * The fleet rule this encodes: a GENERATED migration containing DROP is never
 * approved. Tools that diff a model against a live schema emit
 * `DROP TABLE`/`DROP COLUMN` for anything they cannot see a reason for, and
 * approving one of those against a database that now holds the only copy of the
 * data is unrecoverable. Rather than trusting review to catch it, the test gate
 * calls this and fails.
 *
 * Comments are stripped first so the words can still be DISCUSSED in a comment
 * (this file does exactly that, several times).
 */
export function assertNoDestructiveMigrations(migrations: readonly Migration[] = MIGRATIONS): void {
  for (const m of migrations) {
    const bare = m.sql
      .replace(/--[^\n]*/g, ' ')
      .replace(/\/\*[\s\S]*?\*\//g, ' ');
    const hit = /\b(DROP|TRUNCATE)\b/i.exec(bare);
    if (hit) {
      throw new Error(
        `Migration ${m.id} (${m.name}) contains ${hit[1].toUpperCase()}. ` +
          'Destructive migrations are never approved in this repo — the database now ' +
          'holds the only copy of this app\'s state.',
      );
    }
  }
}

// ── Applying them ────────────────────────────────────────────────────────────

/**
 * Advisory-lock key for the migration step. An arbitrary constant — it only has
 * to be the same in every process that migrates THIS schema, and different from
 * any other advisory lock this app might take later (it takes none today).
 */
const MIGRATION_LOCK_KEY = 3420250807;

const STATE_TABLE = `
  CREATE TABLE IF NOT EXISTS schema_migrations (
    id         integer PRIMARY KEY,
    name       text NOT NULL,
    applied_at bigint NOT NULL
  );
`;

export interface MigrationOutcome {
  /** Ids applied by THIS boot, in order. Empty when the schema was current. */
  applied: number[];
  /** Ids recorded without running, because this boot adopted an existing schema. */
  adopted: number[];
  /** Every id the database now considers applied. */
  current: number[];
}

/** Which of our tables already exist, whatever the migration state says. */
async function existingBaselineTables(h: SqlHandle): Promise<string[]> {
  const rows = await h
    .prepare(
      `SELECT table_name FROM information_schema.tables
        WHERE table_schema = current_schema() AND table_name = ANY(?)
        ORDER BY table_name`,
    )
    .all<{ table_name: string }>(BASELINE_TABLES as string[]);
  return rows.map((r) => r.table_name);
}

/**
 * Bring the database up to date, or refuse.
 *
 * THE ADOPT PATH. A production database paired with this app at publish time
 * can already hold the baseline tables while `schema_migrations` is empty —
 * that is what happens when a schema was created by something other than this
 * migrator. Guessing is not an option: applying the baseline would fail
 * halfway through on the first table that already exists, and skipping it would
 * leave the app running against a schema nobody has checked.
 *
 * So that state is an explicit refusal, and the operator opts in for exactly
 * one boot with `LEADFINDER_DB_ADOPT=1`, which records the baseline as applied
 * WITHOUT running it. Nothing is created, altered or dropped by adopting.
 */
export async function applyMigrations(
  db: Db,
  opts: { adopt?: boolean; migrations?: readonly Migration[] } = {},
): Promise<MigrationOutcome> {
  const migrations = opts.migrations ?? MIGRATIONS;
  assertNoDestructiveMigrations(migrations);

  await db.exec(STATE_TABLE);

  const outcome: MigrationOutcome = { applied: [], adopted: [], current: [] };

  // ONE transaction for the whole set, opened with an advisory lock.
  //
  // The lock is what makes two processes racing to migrate the same database
  // safe — the loser waits, then re-reads the state inside the lock and finds
  // nothing pending. Without it the loser's CREATE TABLE fails with "relation
  // already exists" and the boot dies. This is not hypothetical here: the test
  // gate boots the assembly several times against one cluster, and the
  // persistence proof restarts the server on purpose.
  //
  // PostgreSQL DDL is transactional, so the whole baseline plus its record is
  // atomic: a migration that fails halfway leaves NO tables and NO state,
  // rather than a half-schema the next boot would try to adopt.
  await db.transaction(async (t) => {
    await t.prepare(`SELECT pg_advisory_xact_lock(?)`).run(MIGRATION_LOCK_KEY);

    const appliedRows = await t.prepare(`SELECT id FROM schema_migrations ORDER BY id`).all<{ id: number }>();
    const applied = new Set(appliedRows.map((r) => r.id));
    outcome.current = [...applied];

    const pending = migrations.filter((m) => !applied.has(m.id));
    if (pending.length === 0) return;

    // Is there already a schema here that this migrator did not record?
    //
    // ONLY when it has recorded NOTHING. The adopt path exists for one state: a
    // database whose schema was created by something other than this migrator,
    // so `schema_migrations` is empty while the tables are there. Once even one
    // migration is recorded, this migrator owns the schema and every later
    // migration simply runs.
    //
    // Gating on `pending.length > 0` instead — which is what this did until
    // order L-3.5a — breaks the moment a SECOND migration is ever added: the
    // production database has 001 recorded and all nineteen baseline tables, so
    // the pending 002 would trip the refusal and the app would not boot. Worse,
    // an operator following the error's own instruction would set
    // LEADFINDER_DB_ADOPT=1 and record 002 as applied WITHOUT running it,
    // leaving a table that no later boot would ever create. L-3.5a ships the
    // first post-baseline migration and is therefore the first order to trip it.
    const present = applied.size === 0 ? await existingBaselineTables(t) : [];
    if (present.length > 0) {
      if (!opts.adopt) {
        throw new Error(
          `This database already holds ${present.length} of this app's tables (${present.slice(0, 5).join(', ')}` +
            `${present.length > 5 ? ', …' : ''}) but has no migration state for them. ` +
            'Refusing to guess. If this schema was created by this app and is correct, restart ONCE with ' +
            'LEADFINDER_DB_ADOPT=1 to record migrations ' +
            `${pending.map((m) => m.id).join(', ')} as applied without running them. ` +
            'Nothing is created, altered or dropped by adopting.',
        );
      }
      for (const m of pending) {
        await t
          .prepare(`INSERT INTO schema_migrations (id, name, applied_at) VALUES (?, ?, ?)`)
          .run(m.id, m.name, Date.now());
        outcome.adopted.push(m.id);
        outcome.current.push(m.id);
      }
      return;
    }

    for (const m of pending) {
      await t.exec(m.sql);
      await t
        .prepare(`INSERT INTO schema_migrations (id, name, applied_at) VALUES (?, ?, ?)`)
        .run(m.id, m.name, Date.now());
      outcome.applied.push(m.id);
      outcome.current.push(m.id);
    }
  });

  for (const id of outcome.applied) {
    const m = migrations.find((x) => x.id === id)!;
    log.info(`db: applied migration ${m.id} — ${m.name}`);
  }
  if (outcome.adopted.length > 0) {
    log.warn(
      `db: ADOPTED an existing schema — migrations ${outcome.adopted.join(', ')} recorded as applied ` +
        'without running. Remove LEADFINDER_DB_ADOPT before the next boot.',
    );
  }

  return outcome;
}

// ── offline tests (pure — no database) ───────────────────────────────────────

export function runMigrationsTests(): { passed: number; failed: number; failures: string[] } {
  let passed = 0;
  const failures: string[] = [];
  const check = (cond: boolean, desc: string) => {
    if (cond) passed++;
    else failures.push(`FAIL: ${desc}`);
  };

  check(MIGRATIONS.length > 0, 'migrations: there is at least one');
  check(
    MIGRATIONS.every((m, i) => (i === 0 ? true : m.id > MIGRATIONS[i - 1].id)),
    'migrations: ids are strictly ascending',
  );
  check(new Set(MIGRATIONS.map((m) => m.id)).size === MIGRATIONS.length, 'migrations: ids are unique');
  check(
    MIGRATIONS.every((m) => m.name.trim().length > 0),
    'migrations: every migration is named',
  );

  // The ban, in both directions.
  let banned = false;
  try {
    assertNoDestructiveMigrations([{ id: 99, name: 'generated diff', sql: 'DROP TABLE publishers;' }]);
  } catch {
    banned = true;
  }
  check(banned, 'migrations: a DROP is refused');
  let truncBanned = false;
  try {
    assertNoDestructiveMigrations([{ id: 99, name: 'generated diff', sql: 'truncate table jobs;' }]);
  } catch {
    truncBanned = true;
  }
  check(truncBanned, 'migrations: a lower-case TRUNCATE is refused too');
  let dropColumn = false;
  try {
    assertNoDestructiveMigrations([
      { id: 99, name: 'generated diff', sql: 'ALTER TABLE jobs DROP COLUMN leads_found;' },
    ]);
  } catch {
    dropColumn = true;
  }
  check(dropColumn, 'migrations: DROP COLUMN is refused, not only DROP TABLE');

  let shipped = true;
  try {
    assertNoDestructiveMigrations();
  } catch {
    shipped = false;
  }
  check(shipped, 'migrations: the migrations this app actually ships are non-destructive');

  check(
    /-- .*DROP/i.test('-- a comment mentioning DROP') &&
      (() => {
        try {
          assertNoDestructiveMigrations([{ id: 99, name: 'commented', sql: '-- DROP is never approved\nSELECT 1;' }]);
          return true;
        } catch {
          return false;
        }
      })(),
    'migrations: the words may still be discussed in a comment',
  );

  // Every baseline table must actually appear in the baseline SQL, or the adopt
  // check would look for a table this migration never creates.
  const baselineSql = MIGRATIONS[0].sql;
  const missing = BASELINE_TABLES.filter((t) => !new RegExp(`CREATE TABLE ${t}\\b`).test(baselineSql));
  check(missing.length === 0, `migrations: every listed baseline table is created (missing: ${missing.join(', ')})`);

  // int4 would overflow on epoch-ms. Nothing in the baseline may be `integer`
  // except schema_migrations.id, which is not in this string at all.
  check(!/\binteger\b/i.test(baselineSql), 'migrations: no baseline column is int4 — epoch-ms needs bigint');

  // Identity columns must be BY DEFAULT, or the rescue seed cannot restore a
  // lead under the id the Chief already recorded.
  const identityCount = (baselineSql.match(/GENERATED BY DEFAULT AS IDENTITY/g) ?? []).length;
  check(identityCount === 5, `migrations: all five AUTOINCREMENT keys are BY DEFAULT identities (found ${identityCount})`);
  check(
    !/GENERATED ALWAYS AS IDENTITY/.test(baselineSql),
    'migrations: no identity is ALWAYS — the rescue seed inserts explicit ids',
  );

  // ── 002, the spend cursor (L-3.5a) ──
  const m2 = MIGRATIONS.find((m) => m.id === 2);
  check(!!m2, 'migrations: 002 is shipped');
  check(
    !!m2 && /CREATE TABLE chief_spend_cursor\b/.test(m2.sql),
    'migrations: 002 creates chief_spend_cursor',
  );
  check(
    !!m2 && /PRIMARY KEY \(utc_day, vendor\)/.test(m2.sql),
    'migrations: the cursor is keyed per UTC day per vendor',
  );
  check(
    !!m2 && !/\binteger\b/i.test(m2.sql),
    'migrations: 002 uses bigint, not int4 — updated_at is epoch-ms',
  );
  // The cursor is NOT a baseline table. Listing it would make the adopt check
  // look for a table migration 001 never creates.
  check(
    !BASELINE_TABLES.includes('chief_spend_cursor'),
    'migrations: the cursor is not claimed by the baseline',
  );

  return { passed, failed: failures.length, failures };
}

